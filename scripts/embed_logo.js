// ==============================================================================
// Mejde Network - Brand Logo Embedder & Asset Synchronizer
// Reads the brand logo, encodes to Base64 for WebView inlining, and copies to targets
// ==============================================================================

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const candidatePaths = [
  'C:\\Users\\Azzeddine\\.gemini\\antigravity-ide\\brain\\12d44af2-4ec7-47c3-a4c6-3f8bd48b55ba\\.user_uploaded\\media_1790553660025.png',
  path.join(projectRoot, 'public', 'logo.png'),
  path.join(projectRoot, 'frontend', 'public', 'logo.png'),
  path.join(projectRoot, 'installer', 'logo.png'),
  path.join(projectRoot, 'android', 'assets', 'icon.png')
];

let sourcePath = null;
for (const p of candidatePaths) {
  if (fs.existsSync(p)) {
    sourcePath = p;
    break;
  }
}

if (!sourcePath) {
  console.warn('[Warning] No brand logo source found in candidate paths.');
  // If brandLogo.js already exists, don't overwrite it
  const destBrandJs = path.join(projectRoot, 'frontend', 'src', 'lib', 'brandLogo.js');
  if (!fs.existsSync(destBrandJs)) {
    fs.writeFileSync(destBrandJs, 'export const BRAND_LOGO = "";\n');
  }
} else {
  const logoBuffer = fs.readFileSync(sourcePath);
  const base64Data = logoBuffer.toString('base64');
  const dataUri = `data:image/png;base64,${base64Data}`;

  // 1. Write brandLogo.js for direct Svelte inlining (zero-path WebView safe)
  const brandJsContent = `// Auto-generated by scripts/embed_logo.js\nexport const BRAND_LOGO = "${dataUri}";\n`;
  const destBrandJs = path.join(projectRoot, 'frontend', 'src', 'lib', 'brandLogo.js');
  fs.writeFileSync(destBrandJs, brandJsContent);
  console.log(`[Brand] Wrote brandLogo.js with Base64 data URI (${base64Data.length} chars)`);

  // 2. Generate standard Windows ICO file from PNG buffer
  function createIcoFromPng(pngBuf) {
    let width = 0;
    let height = 0;
    if (pngBuf.length >= 24) {
      width = pngBuf.readUInt32BE(16);
      height = pngBuf.readUInt32BE(20);
    }
    console.log(`[Brand] Source PNG dimensions: ${width}x${height}`);

    const icoWidth = (width >= 256 || width <= 0) ? 0 : width;
    const icoHeight = (height >= 256 || height <= 0) ? 0 : height;

    const header = Buffer.alloc(6);
    header.writeUInt16LE(0, 0); // Reserved
    header.writeUInt16LE(1, 2); // 1 = ICO
    header.writeUInt16LE(1, 4); // 1 image

    const entry = Buffer.alloc(16);
    entry.writeUInt8(icoWidth, 0);
    entry.writeUInt8(icoHeight, 1);
    entry.writeUInt8(0, 2); // Palette: 0
    entry.writeUInt8(0, 3); // Reserved: 0
    entry.writeUInt16LE(1, 4); // Color planes
    entry.writeUInt16LE(32, 6); // Bits per pixel
    entry.writeUInt32LE(pngBuf.length, 8); // Size of image data
    entry.writeUInt32LE(22, 12); // Offset (6 header + 16 entry = 22)

    return Buffer.concat([header, entry, pngBuf]);
  }

  const icoBuffer = createIcoFromPng(logoBuffer);
  fs.writeFileSync(path.join(projectRoot, 'public', 'logo.ico'), icoBuffer);
  fs.writeFileSync(path.join(projectRoot, 'installer', 'logo.ico'), icoBuffer);
  fs.writeFileSync(path.join(projectRoot, 'frontend', 'public', 'favicon.ico'), icoBuffer);
  console.log('[Brand] Generated Windows .ico format for installer and desktop shortcuts.');

  // 3. Ensure directories exist
  const targets = [
    path.join(projectRoot, 'public', 'logo.png'),
    path.join(projectRoot, 'public', 'icon.png'),
    path.join(projectRoot, 'frontend', 'public', 'logo.png'),
    path.join(projectRoot, 'frontend', 'public', 'favicon.png'),
    path.join(projectRoot, 'installer', 'logo.png'),
    path.join(projectRoot, 'android', 'assets', 'icon.png'),
    path.join(projectRoot, 'assets', 'icon.png'),
    path.join(projectRoot, 'res', 'mipmap-mdpi', 'ic_launcher.png'),
    path.join(projectRoot, 'res', 'mipmap-hdpi', 'ic_launcher.png'),
    path.join(projectRoot, 'res', 'mipmap-xhdpi', 'ic_launcher.png'),
    path.join(projectRoot, 'res', 'mipmap-xxhdpi', 'ic_launcher.png'),
    path.join(projectRoot, 'res', 'mipmap-xxxhdpi', 'ic_launcher.png')
  ];

  for (const target of targets) {
    const dir = path.dirname(target);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(target, logoBuffer);
  }
  console.log(`[Brand] Synchronized brand logo to ${targets.length} target asset locations.`);
}

